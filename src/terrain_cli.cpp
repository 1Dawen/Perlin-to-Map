#include "terrain/terrain.hpp"

#include <algorithm>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <stdexcept>
#include <string>

namespace fs = std::filesystem;

namespace {
void writePpm(const fs::path& path, const terrain::Mesh& mesh, int grid) {
    fs::create_directories(path.parent_path().empty() ? fs::path(".") : path.parent_path());
    std::ofstream out(path, std::ios::binary);
    if (!out) throw std::runtime_error("Cannot write PPM file: " + path.string());
    const int size = grid + 1;
    out << "P6\n" << size << " " << size << "\n255\n";
    for (const auto& vertex : mesh.vertices) {
        for (float color : {vertex.color.x, vertex.color.y, vertex.color.z}) {
            const auto channel = static_cast<unsigned char>(std::clamp(color, 0.0f, 1.0f) * 255.0f);
            out.write(reinterpret_cast<const char*>(&channel), 1);
        }
    }
    if (!out) throw std::runtime_error("Failed to finish writing PPM file");
}

void writeObj(const fs::path& path, const terrain::Mesh& mesh) {
    fs::create_directories(path.parent_path().empty() ? fs::path(".") : path.parent_path());
    std::ofstream out(path);
    if (!out) throw std::runtime_error("Cannot write OBJ file: " + path.string());
    out << "# Procedural terrain generated by perlin-terrain-generator\n";
    for (const auto& v : mesh.vertices) {
        out << "v " << v.position.x << ' ' << v.position.y << ' ' << v.position.z << '\n';
    }
    for (const auto& v : mesh.vertices) {
        out << "vn " << v.normal.x << ' ' << v.normal.y << ' ' << v.normal.z << '\n';
    }
    for (std::size_t k = 0; k < mesh.indices.size(); k += 3) {
        out << "f ";
        for (int j = 0; j < 3; ++j) {
            const auto id = mesh.indices[k + j] + 1;
            out << id << "//" << id << (j < 2 ? ' ' : '\n');
        }
    }
    if (!out) throw std::runtime_error("Failed to finish writing OBJ file");
}
} // namespace

int main(int argc, char** argv) {
    try {
        terrain::Settings settings;
        fs::path ppm = "outputs/terrain.ppm";
        fs::path obj;
        for (int i = 1; i < argc; ++i) {
            const std::string key = argv[i];
            auto value = [&]() -> std::string {
                if (i + 1 >= argc) throw std::invalid_argument("Missing value after " + key);
                return argv[++i];
            };
            if (key == "--help") {
                std::cout << "Usage: terrain_cli [--grid N] [--seed N] [--island] [--terrace] "
                          << "[--ridged-mix 0..1] [--output output.ppm] [--obj output.obj]\n";
                return 0;
            }
            if (key == "--grid") settings.gridSize = std::stoi(value());
            else if (key == "--seed") settings.seed = static_cast<std::uint32_t>(std::stoul(value()));
            else if (key == "--island") settings.islandEnabled = true;
            else if (key == "--terrace") settings.terraceEnabled = true;
            else if (key == "--ridged-mix") settings.ridgedMix = std::stof(value());
            else if (key == "--output") ppm = value();
            else if (key == "--obj") obj = value();
            else throw std::invalid_argument("Unknown option: " + key);
        }
        terrain::TerrainGenerator generator(settings);
        const auto mesh = generator.generate();
        writePpm(ppm, mesh, settings.gridSize);
        if (!obj.empty()) writeObj(obj, mesh);
        std::cout << "Generated " << mesh.vertices.size() << " vertices, "
                  << mesh.indices.size() / 3 << " triangles.\n"
                  << "Top-down biome colors: " << ppm << '\n';
        if (!obj.empty()) std::cout << "3D mesh: " << obj << '\n';
    } catch (const std::exception& error) {
        std::cerr << "Error: " << error.what() << '\n';
        return 1;
    }
}
